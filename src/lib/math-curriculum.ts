export function getMathCurriculumContext(grade: string, topics: string[]) {
  const gradeContext = mathCurriculum[grade];
  if (!gradeContext) return [];

  return topics
    .map((topic) => ({ topic, scope: gradeContext[topic] }))
    .filter((item): item is { topic: string; scope: string } => Boolean(item.scope));
}
